-- Class_type(class_type_id, name, description, skill_level, duration_minutes)
CREATE TABLE class_type (
    class_type_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name              VARCHAR(100) NOT NULL,
    description       TEXT,
    skill_level       VARCHAR(20)  NOT NULL,
    duration_minutes  INTEGER      NOT NULL,

