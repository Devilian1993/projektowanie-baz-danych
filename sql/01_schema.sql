BEGIN;

DROP TABLE IF EXISTS
    wymagany_sprzet, cwiczenia_w_planie, cwiczenie, plan_treningowy,
    zapisy_zajecia, zajecia_grupowe, kwalifikacje_trenera, rodzaj_zajec,
    rezerwacja_stanowiska, platnosc_trening, trening_personalny,
    zgloszenie_serwisowe, maszyna, model_maszyny, stanowisko,
    platnosc_karnet, platnosc, karnet, typ_karnetu, wejscie,
    administrator, pracownik_techniczny, recepcjonista,
    trener_specjalizacja, specjalizacja, trener, klient,
    nieudane_logowanie, konto_uzytkownika, kategoria_sprzetu, sala
    CASCADE;

DROP DOMAIN IF EXISTS valid_email, valid_phone, valid_login;

-- E-mail address
CREATE DOMAIN valid_email AS VARCHAR(254)
CHECK (
    VALUE ~* '^[A-Za-z0-9._+%-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'
);

-- Phone number (contains only digits)
CREATE DOMAIN valid_phone AS VARCHAR(15)
CHECK (
    VALUE ~ '^[0-9]{9,15}$'
);

-- Login (can contain letters, numbers, dashes and underscores)
CREATE DOMAIN valid_login AS VARCHAR(50)
CHECK (
    VALUE ~ '^[A-Za-z0-9_-]+$'
);

-- Sala(id_sali, numer, nazwa, powierzchnia, maks_liczba_osob,
--      godzina_otwarcia, godzina_zamkniecia, status_dostepnosci)
CREATE TABLE sala (
    id_sali             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    numer               INTEGER       NOT NULL,
    nazwa               VARCHAR(100)  NOT NULL,
    powierzchnia        NUMERIC(7,2),
    maks_liczba_osob    INTEGER       NOT NULL,
    godzina_otwarcia    TIME          NOT NULL DEFAULT '00:00',
    godzina_zamkniecia  TIME          NOT NULL DEFAULT '23:59:59',
    czy_aktywna         BOOLEAN       NOT NULL DEFAULT TRUE,

--     status_dostepnosci  VARCHAR(15)   NOT NULL DEFAULT 'dostepna' CHECK (status_dostepnosci IN ('dostepna', 'niedostepna')),

    CONSTRAINT pk_sala                 PRIMARY KEY (id_sali),
    CONSTRAINT uq_sala_numer           UNIQUE (numer),
    CONSTRAINT uq_sala_nazwa           UNIQUE (nazwa),

    CONSTRAINT chk_sala_numer          CHECK (numer >= 0),
    CONSTRAINT chk_sala_powierzchnia   CHECK (powierzchnia > 0),
    CONSTRAINT chk_sala_maks_osob      CHECK (maks_liczba_osob > 0),
    CONSTRAINT chk_sala_przedz_cz      CHECK (godzina_zamkniecia > godzina_otwarcia)
);

-- Kategoria_sprzetu(id_kategorii, nazwa, opis)
CREATE TABLE kategoria_sprzetu (
    id_kategorii  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nazwa         VARCHAR(100) NOT NULL,
    opis          TEXT,

    CONSTRAINT pk_kategoria_sprzetu  PRIMARY KEY (id_kategorii),
    CONSTRAINT uq_kategoria_nazwa    UNIQUE (nazwa)
);

-- Konto_uzytkownika(id_konta, login, email, hash_hasla, nr_karty_dostepu,
--                   status, data_utworzenia, data_ost_logowania)
CREATE TABLE konto_uzytkownika (
    id_konta            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    login               valid_login   NOT NULL,
    email               valid_email   NOT NULL,
    hash_hasla          VARCHAR(255)  NOT NULL,
    nr_karty_dostepu    INTEGER       NOT NULL,
--     status              VARCHAR(15)   NOT NULL DEFAULT 'aktywne'         CHECK (status IN ('aktywne', 'nieaktywne')),
    czy_aktywne         BOOLEAN       NOT NULL DEFAULT TRUE,
    data_utworzenia     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_ost_logowania  TIMESTAMP,

    CONSTRAINT pk_konto_uzytkownika  PRIMARY KEY (id_konta),
    CONSTRAINT uq_konto_login        UNIQUE (login),
    CONSTRAINT uq_konto_email        UNIQUE (email),
    CONSTRAINT uq_konto_karta        UNIQUE (nr_karty_dostepu),

    CONSTRAINT chk_konto_nr_karty    CHECK (nr_karty_dostepu >= 0),
    CONSTRAINT chk_konto_przedz_cz   CHECK (data_ost_logowania >= data_utworzenia)
);

-- Nieudane_logowanie(id_proby, #id_konta, data_proby)
CREATE TABLE nieudane_logowanie (
    id_proby    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_konta    INTEGER    NOT NULL,
    data_proby  TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_nieudane_logowanie  PRIMARY KEY (id_proby),
    CONSTRAINT fk_nieudane_konto      FOREIGN KEY (id_konta)
        REFERENCES konto_uzytkownika (id_konta) ON DELETE CASCADE
);

-- Klient(id_klienta, #id_konta, imie, nazwisko, telefon,
--        data_rejestracji, status_studenta)
CREATE TABLE klient (
    id_klienta        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_konta          INTEGER       NOT NULL,
    imie              VARCHAR(50)   NOT NULL,
    nazwisko          VARCHAR(80)   NOT NULL,
    telefon           valid_phone,
    data_rejestracji  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status_studenta   BOOLEAN       NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_klient        PRIMARY KEY (id_klienta),
    CONSTRAINT uq_klient_konto  UNIQUE (id_konta),
    CONSTRAINT fk_klient_konto  FOREIGN KEY (id_konta)
        REFERENCES konto_uzytkownika (id_konta) ON DELETE CASCADE
);

-- Trener(id_trenera, #id_konta, imie, nazwisko, telefon,
--        data_zatrudnienia, stawka_trening)
CREATE TABLE trener (
    id_trenera         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_konta           INTEGER        NOT NULL,
    imie               VARCHAR(50)    NOT NULL,
    nazwisko           VARCHAR(80)    NOT NULL,
    telefon            valid_phone,
    data_zatrudnienia  DATE           NOT NULL DEFAULT CURRENT_DATE,
    -- NULL: trener prowadzi tylko zajęcia grupowe
    stawka_trening     NUMERIC(10,2),

    CONSTRAINT pk_trener          PRIMARY KEY (id_trenera),
    CONSTRAINT uq_trener_konto    UNIQUE (id_konta),
    CONSTRAINT fk_trener_konto    FOREIGN KEY (id_konta)
        REFERENCES konto_uzytkownika (id_konta) ON DELETE CASCADE,

    CONSTRAINT chk_trener_stawka  CHECK (stawka_trening >= 0)
);

-- Specjalizacja(id_specjalizacji, nazwa, opis)
CREATE TABLE specjalizacja (
    id_specjalizacji  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nazwa             VARCHAR(100) NOT NULL,
    opis              TEXT,

    CONSTRAINT pk_specjalizacja        PRIMARY KEY (id_specjalizacji),
    CONSTRAINT uq_specjalizacja_nazwa  UNIQUE (nazwa)
);

-- Trener_specjalizacja(#id_trenera, #id_specjalizacji)
CREATE TABLE trener_specjalizacja (
    id_trenera        INTEGER NOT NULL,
    id_specjalizacji  INTEGER NOT NULL,

    CONSTRAINT pk_trener_specjalizacja  PRIMARY KEY (id_trenera, id_specjalizacji),
    CONSTRAINT fk_ts_trener             FOREIGN KEY (id_trenera)
        REFERENCES trener (id_trenera) ON DELETE CASCADE,
    CONSTRAINT fk_ts_specjalizacja      FOREIGN KEY (id_specjalizacji)
        REFERENCES specjalizacja (id_specjalizacji) ON DELETE CASCADE
);

-- Recepcjonista(id_recepcjonisty, #id_konta, imie, nazwisko, telefon, data_zatrudnienia)
CREATE TABLE recepcjonista (
    id_recepcjonisty   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_konta           INTEGER       NOT NULL,
    imie               VARCHAR(50)   NOT NULL,
    nazwisko           VARCHAR(80)   NOT NULL,
    telefon            valid_phone,
    data_zatrudnienia  DATE          NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_recepcjonista        PRIMARY KEY (id_recepcjonisty),
    CONSTRAINT uq_recepcjonista_konto  UNIQUE (id_konta),
    CONSTRAINT fk_recepcjonista_konto  FOREIGN KEY (id_konta)
        REFERENCES konto_uzytkownika (id_konta) ON DELETE CASCADE
);

-- Pracownik_techniczny(id_technicznego, #id_konta, imie, nazwisko, telefon, data_zatrudnienia)
CREATE TABLE pracownik_techniczny (
    id_technicznego    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_konta           INTEGER       NOT NULL,
    imie               VARCHAR(50)   NOT NULL,
    nazwisko           VARCHAR(80)   NOT NULL,
    telefon            valid_phone,
    data_zatrudnienia  DATE          NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_pracownik_techniczny  PRIMARY KEY (id_technicznego),
    CONSTRAINT uq_techniczny_konto      UNIQUE (id_konta),
    CONSTRAINT fk_techniczny_konto      FOREIGN KEY (id_konta)
        REFERENCES konto_uzytkownika (id_konta) ON DELETE CASCADE
);

-- Administrator(id_administratora, #id_konta, imie, nazwisko, telefon)
CREATE TABLE administrator (
    id_administratora  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_konta           INTEGER       NOT NULL,
    imie               VARCHAR(50)   NOT NULL,
    nazwisko           VARCHAR(80)   NOT NULL,
    telefon            valid_phone,

    CONSTRAINT pk_administrator        PRIMARY KEY (id_administratora),
    CONSTRAINT uq_administrator_konto  UNIQUE (id_konta),
    CONSTRAINT fk_administrator_konto  FOREIGN KEY (id_konta)
        REFERENCES konto_uzytkownika (id_konta) ON DELETE CASCADE
);

-- Wejscie(id_wejscia, #id_konta, data_wejscia, data_wyjscia, wynik, powod_odmowy)
CREATE TABLE wejscie (
    id_wejscia     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_konta       INTEGER       NOT NULL,
    data_wejscia   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_wyjscia   TIMESTAMP,
    wynik          BOOLEAN       NOT NULL,
    powod_odmowy   VARCHAR(255),

    CONSTRAINT pk_wejscie             PRIMARY KEY (id_wejscia),
    CONSTRAINT fk_wejscie_konto       FOREIGN KEY (id_konta)
        REFERENCES konto_uzytkownika (id_konta) ON DELETE CASCADE,

    CONSTRAINT chk_wejscie_przedz_cz  CHECK (data_wyjscia > data_wejscia),
    CONSTRAINT chk_wejscie_wynik      CHECK (wynik OR data_wyjscia IS NULL)
);

-- Typ_karnetu(id_typu, nazwa, okres_waznosci, cena_normalna, cena_ulgowa, opis)
CREATE TABLE typ_karnetu (
    id_typu         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nazwa           VARCHAR(50)    NOT NULL,
    -- w dniach
    okres_waznosci  INTEGER        NOT NULL,
    cena_normalna   NUMERIC(10,2)  NOT NULL,
    cena_ulgowa     NUMERIC(10,2)  NOT NULL,
    opis            TEXT,

    CONSTRAINT pk_typ_karnetu          PRIMARY KEY (id_typu),
    CONSTRAINT uq_typ_nazwa            UNIQUE (nazwa),

    CONSTRAINT chk_typ_okres           CHECK (okres_waznosci >= 1),
    CONSTRAINT chk_typ_cena_normalna   CHECK (cena_normalna >= 0),
    CONSTRAINT chk_typ_cena_ulgowa     CHECK (cena_ulgowa >= 0)
);

-- Karnet(id_karnetu, #id_klienta, #id_typu, #id_recepcjonisty,
--        data_zakupu, data_rozpoczecia, status, cena)
CREATE TABLE karnet (
    id_karnetu        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_klienta        INTEGER        NOT NULL,
    id_typu           INTEGER        NOT NULL,
    id_recepcjonisty  INTEGER,
    data_zakupu       TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_rozpoczecia  DATE           NOT NULL DEFAULT CURRENT_DATE,
--     status            VARCHAR(15)    NOT NULL DEFAULT 'oczekujacy'      CHECK (status IN ('oczekujacy', 'aktywny', 'przedawniony')),
    cena              NUMERIC(10,2)  NOT NULL,

    CONSTRAINT pk_karnet                PRIMARY KEY (id_karnetu),
    CONSTRAINT fk_karnet_klient         FOREIGN KEY (id_klienta)
        REFERENCES klient (id_klienta) ON DELETE CASCADE,
    CONSTRAINT fk_karnet_typ            FOREIGN KEY (id_typu)
        REFERENCES typ_karnetu (id_typu) ON DELETE RESTRICT,
    CONSTRAINT fk_karnet_recepcjonista  FOREIGN KEY (id_recepcjonisty)
        REFERENCES recepcjonista (id_recepcjonisty) ON DELETE SET NULL,

    CONSTRAINT chk_karnet_cena          CHECK (cena >= 0),
    CONSTRAINT chk_karnet_przedz_cz     CHECK (data_rozpoczecia >= data_zakupu::date)
);

-- Platnosc(id_platnosci, kwota, data, forma, tytul, status)
CREATE TABLE platnosc (
    id_platnosci  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    kwota         NUMERIC(10,2)  NOT NULL,
    data          TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    forma         VARCHAR(15)    NOT NULL,
    tytul         VARCHAR(20)    NOT NULL,
    status        VARCHAR(15)    NOT NULL DEFAULT 'oczekujaca',

    CONSTRAINT pk_platnosc         PRIMARY KEY (id_platnosci),

    CONSTRAINT chk_platnosc_kwota  CHECK (kwota >= 0),
    CONSTRAINT chk_platnosc_forma  CHECK (forma IN ('gotowka', 'blik', 'karta')),
    CONSTRAINT chk_platnosc_status CHECK (status IN ('oczekujaca', 'oplacona', 'odrzucona'))
);

-- Platnosc_karnet(#id_platnosci, #id_karnetu)
CREATE TABLE platnosc_karnet (
    id_platnosci  INTEGER NOT NULL,
    id_karnetu    INTEGER NOT NULL,

    CONSTRAINT pk_platnosc_karnet  PRIMARY KEY (id_platnosci, id_karnetu),
    CONSTRAINT fk_pk_platnosc      FOREIGN KEY (id_platnosci)
        REFERENCES platnosc (id_platnosci) ON DELETE CASCADE,
    CONSTRAINT fk_pk_karnet        FOREIGN KEY (id_karnetu)
        REFERENCES karnet (id_karnetu) ON DELETE CASCADE
);

-- Stanowisko(id_stanowiska, #id_sali, nazwa, opis, status_dostepnosci)
CREATE TABLE stanowisko (
    id_stanowiska       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_sali             INTEGER       NOT NULL,
    nazwa               VARCHAR(100)  NOT NULL,
    opis                TEXT,
    czy_dostepne        BOOLEAN       NOT NULL DEFAULT TRUE,
--     status_dostepnosci  VARCHAR(15)   NOT NULL DEFAULT 'dostepne' CHECK (status_dostepnosci IN ('dostepne', 'niedostepne')),

    CONSTRAINT pk_stanowisko       PRIMARY KEY (id_stanowiska),
    CONSTRAINT fk_stanowisko_sala  FOREIGN KEY (id_sali)
        REFERENCES sala (id_sali) ON DELETE CASCADE
);

-- Model_maszyny(id_modelu, #id_kategorii, producent, model, nazwa)
CREATE TABLE model_maszyny (
    id_modelu     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_kategorii  INTEGER       NOT NULL,
    producent     VARCHAR(100)  NOT NULL,
    model         VARCHAR(100)  NOT NULL,
    nazwa         VARCHAR(150),

    CONSTRAINT pk_model_maszyny    PRIMARY KEY (id_modelu),
    CONSTRAINT uq_model_producent  UNIQUE (producent, model),
    CONSTRAINT fk_model_kategoria  FOREIGN KEY (id_kategorii)
        REFERENCES kategoria_sprzetu (id_kategorii) ON DELETE RESTRICT
);

-- Maszyna(id_maszyny, #id_stanowiska, #id_modelu, nr_seryjny,
--         data_zakupu, stan_techniczny, data_konserwacji)
CREATE TABLE maszyna (
    id_maszyny        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_stanowiska     INTEGER,                  -- NULL: maszyna w magazynie / w serwisie
    id_modelu         INTEGER       NOT NULL,
    nr_seryjny        VARCHAR(50)   NOT NULL,
    data_zakupu       DATE          NOT NULL,
    stan_techniczny   VARCHAR(20)   NOT NULL DEFAULT 'sprawna',
    data_konserwacji  DATE,

    CONSTRAINT pk_maszyna             PRIMARY KEY (id_maszyny),
    CONSTRAINT uq_maszyna_nr          UNIQUE (id_modelu, nr_seryjny),
    CONSTRAINT fk_maszyna_stanowisko  FOREIGN KEY (id_stanowiska)
        REFERENCES stanowisko (id_stanowiska) ON DELETE SET NULL,
    CONSTRAINT fk_maszyna_model       FOREIGN KEY (id_modelu)
        REFERENCES model_maszyny (id_modelu) ON DELETE CASCADE,

    CONSTRAINT chk_maszyna_stan       CHECK (stan_techniczny IN ('sprawna', 'uszkodzona', 'w_konserwacji')),
    CONSTRAINT chk_maszyna_przedz_cz  CHECK (data_konserwacji >= data_zakupu)
);

-- Zgloszenie_serwisowe(id_zgloszenia, #id_maszyny, #id_konta_zglaszajacego,
--   #id_technicznego, rodzaj, data_zgloszenia, opis, status,
--   data_rozpoczecia, data_zakonczenia)
CREATE TABLE zgloszenie_serwisowe (
    id_zgloszenia           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_maszyny              INTEGER       NOT NULL,
    id_konta_zglaszajacego  INTEGER,
    id_technicznego         INTEGER,                  -- NULL: jeszcze nie przydzielono technika
    rodzaj                  VARCHAR(25)   NOT NULL,
    data_zgloszenia         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    opis                    TEXT          NOT NULL,
--     status                  VARCHAR(15)   NOT NULL DEFAULT 'zgloszone'       CHECK (status IN ('zgloszone', 'w_realizacji', 'zakonczone', 'odrzucone')),
    data_rozpoczecia        TIMESTAMP,                -- NULL do chwili podjęcia naprawy
    data_zakonczenia        TIMESTAMP,

    CONSTRAINT pk_zgloszenie_serwisowe   PRIMARY KEY (id_zgloszenia),
    CONSTRAINT fk_zgloszenie_maszyna     FOREIGN KEY (id_maszyny)
        REFERENCES maszyna (id_maszyny) ON DELETE CASCADE,
    CONSTRAINT fk_zgloszenie_konto       FOREIGN KEY (id_konta_zglaszajacego)
        REFERENCES konto_uzytkownika (id_konta) ON DELETE SET NULL,
    CONSTRAINT fk_zgloszenie_techniczny  FOREIGN KEY (id_technicznego)
        REFERENCES pracownik_techniczny (id_technicznego) ON DELETE SET NULL,

    CONSTRAINT chk_zgloszenie_rodzaj     CHECK (rodzaj IN ('rutynowa_konserwacja', 'uszkodzona_czesc', 'brakujaca_czesc', 'zuzyta_czesc')),
    CONSTRAINT chk_zgloszenie_start      CHECK (data_rozpoczecia >= data_zgloszenia),
    CONSTRAINT chk_zgloszenie_koniec     CHECK (data_zakonczenia > data_rozpoczecia),
    CONSTRAINT chk_zgloszenie_valid_cz   CHECK (data_zakonczenia IS NULL OR data_rozpoczecia IS NOT NULL)
);

-- Trening_personalny(id_treningu, #id_klienta, #id_trenera,
--                    czas_od, czas_do, cena, status, uwagi)
CREATE TABLE trening_personalny (
    id_treningu  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_klienta   INTEGER        NOT NULL,
    id_trenera   INTEGER        NOT NULL,
    czas_od      TIMESTAMP      NOT NULL,
    czas_do      TIMESTAMP      NOT NULL,
    -- cena z chwili umówienia treningu
    cena         NUMERIC(10,2)  NOT NULL,
    czy_odwolany BOOLEAN        NOT NULL DEFAULT FALSE,
--     status       VARCHAR(15)    NOT NULL DEFAULT 'zaplanowany'  CHECK (status IN ('zaplanowany', 'trwajacy', 'zakonczony')),
    uwagi        TEXT,

    CONSTRAINT pk_trening_personalny  PRIMARY KEY (id_treningu),
    CONSTRAINT fk_trening_klient      FOREIGN KEY (id_klienta)
        REFERENCES klient (id_klienta) ON DELETE CASCADE,
    CONSTRAINT fk_trening_trener      FOREIGN KEY (id_trenera)
        REFERENCES trener (id_trenera) ON DELETE CASCADE,

    CONSTRAINT chk_trening_cena       CHECK (cena >= 0),
    CONSTRAINT chk_trening_przedz_cz  CHECK (czas_do > czas_od)
);

-- Platnosc_trening(#id_platnosci, #id_treningu)
CREATE TABLE platnosc_trening (
    id_platnosci  INTEGER NOT NULL,
    id_treningu   INTEGER NOT NULL,

    CONSTRAINT pk_platnosc_trening  PRIMARY KEY (id_platnosci, id_treningu),
    CONSTRAINT fk_pt_platnosc       FOREIGN KEY (id_platnosci)
        REFERENCES platnosc (id_platnosci) ON DELETE CASCADE,
    CONSTRAINT fk_pt_trening        FOREIGN KEY (id_treningu)
        REFERENCES trening_personalny (id_treningu) ON DELETE CASCADE
);

-- Rezerwacja_stanowiska(id_rezerwacji, #id_stanowiska, #id_treningu,
--                       rez_od, rez_do, data_utworzenia, status)
CREATE TABLE rezerwacja_stanowiska (
    id_rezerwacji    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_stanowiska    INTEGER      NOT NULL,
    id_treningu      INTEGER      NOT NULL,
    rez_od           TIMESTAMP    NOT NULL,
    rez_do           TIMESTAMP    NOT NULL,
    data_utworzenia  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    czy_aktywna      BOOLEAN      NOT NULL DEFAULT TRUE,
--     status           VARCHAR(15)  NOT NULL DEFAULT 'aktywna'          CHECK (status IN ('aktywna', 'nieaktywna')),

    CONSTRAINT pk_rezerwacja_stanowiska  PRIMARY KEY (id_rezerwacji),
    CONSTRAINT fk_rezerwacja_stanowisko  FOREIGN KEY (id_stanowiska)
        REFERENCES stanowisko (id_stanowiska) ON DELETE CASCADE,
    CONSTRAINT fk_rezerwacja_trening     FOREIGN KEY (id_treningu)
        REFERENCES trening_personalny (id_treningu) ON DELETE CASCADE,

    CONSTRAINT chk_rezerwacja_przedz_cz  CHECK (rez_do > rez_od)
);

-- Rodzaj_zajec(id_rodzaju, nazwa, opis, poziom_zaawansowania, czas_trwania_minuty)
CREATE TABLE rodzaj_zajec (
    id_rodzaju            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nazwa                 VARCHAR(100) NOT NULL,
    opis                  TEXT,
    poziom_zaawansowania  VARCHAR(20)  NOT NULL,
    czas_trwania_minuty   INTEGER      NOT NULL,

    CONSTRAINT pk_rodzaj_zajec    PRIMARY KEY (id_rodzaju),
    CONSTRAINT uq_rodzaj_nazwa    UNIQUE (nazwa),

    CONSTRAINT chk_rodzaj_poziom  CHECK (poziom_zaawansowania IN ('poczatkujacy', 'sredniozaawansowany', 'zaawansowany')),
    CONSTRAINT chk_rodzaj_czas    CHECK (czas_trwania_minuty > 0)
);

-- Kwalifikacje_trenera(#id_trenera, #id_rodzaju)
CREATE TABLE kwalifikacje_trenera (
    id_trenera  INTEGER NOT NULL,
    id_rodzaju  INTEGER NOT NULL,

    CONSTRAINT pk_kwalifikacje_trenera  PRIMARY KEY (id_trenera, id_rodzaju),
    CONSTRAINT fk_kw_trener             FOREIGN KEY (id_trenera)
        REFERENCES trener (id_trenera) ON DELETE CASCADE,
    CONSTRAINT fk_kw_rodzaj             FOREIGN KEY (id_rodzaju)
        REFERENCES rodzaj_zajec (id_rodzaju) ON DELETE CASCADE
);

-- Zajecia_grupowe(id_zajec, #id_rodzaju, #id_sali, #id_trenera,
--                 grup_od, limit_miejsc, status)
CREATE TABLE zajecia_grupowe (
    id_zajec      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_rodzaju    INTEGER      NOT NULL,
    id_sali       INTEGER      NOT NULL,
    id_trenera    INTEGER      NOT NULL,
    grup_od       TIMESTAMP    NOT NULL,
    limit_miejsc  INTEGER      NOT NULL,
    czy_odwolane  BOOLEAN      NOT NULL DEFAULT FALSE,
--     status        VARCHAR(15)  NOT NULL DEFAULT 'zaplanowane' CHECK (status in ('zaplanowane', 'w_trakcie', 'odwolane', 'odbyte')),

    CONSTRAINT pk_zajecia_grupowe  PRIMARY KEY (id_zajec),
    CONSTRAINT fk_zajecia_rodzaj   FOREIGN KEY (id_rodzaju)
        REFERENCES rodzaj_zajec (id_rodzaju) ON DELETE CASCADE,
    CONSTRAINT fk_zajecia_sala     FOREIGN KEY (id_sali)
        REFERENCES sala (id_sali) ON DELETE CASCADE,
    CONSTRAINT fk_zajecia_trener   FOREIGN KEY (id_trenera)
        REFERENCES trener (id_trenera) ON DELETE CASCADE,

    CONSTRAINT chk_zajecia_limit   CHECK (limit_miejsc > 0)
);

-- Zapisy_zajecia(#id_klienta, #id_zajec, data_zapisu)
CREATE TABLE zapisy_zajecia (
    id_klienta   INTEGER    NOT NULL,
    id_zajec     INTEGER    NOT NULL,
    data_zapisu  TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_zapisy_zajecia  PRIMARY KEY (id_klienta, id_zajec),
    CONSTRAINT fk_zapisy_klient   FOREIGN KEY (id_klienta)
        REFERENCES klient (id_klienta) ON DELETE CASCADE,
    CONSTRAINT fk_zapisy_zajecia  FOREIGN KEY (id_zajec)
        REFERENCES zajecia_grupowe (id_zajec) ON DELETE CASCADE
);

-- Plan_treningowy(id_planu, #id_klienta, #id_trenera, nazwa, cel,
--                 obowiazuje_od, obowiazuje_do, zalecenia)
CREATE TABLE plan_treningowy (
    id_planu       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_klienta     INTEGER       NOT NULL,
    id_trenera     INTEGER       NOT NULL,
    nazwa          VARCHAR(100)  NOT NULL,
    cel            VARCHAR(255),
    obowiazuje_od  DATE          NOT NULL,
    obowiazuje_do  DATE          NOT NULL,
    zalecenia      TEXT,

    CONSTRAINT pk_plan_treningowy  PRIMARY KEY (id_planu),
    CONSTRAINT fk_plan_klient      FOREIGN KEY (id_klienta)
        REFERENCES klient (id_klienta) ON DELETE CASCADE,
    CONSTRAINT fk_plan_trener      FOREIGN KEY (id_trenera)
        REFERENCES trener (id_trenera) ON DELETE CASCADE,

    CONSTRAINT chk_plan_przedz_cz  CHECK (obowiazuje_do >= obowiazuje_od)
);

-- Cwiczenie(id_cwiczenia, nazwa, opis, poziom_trudnosci)
CREATE TABLE cwiczenie (
    id_cwiczenia      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nazwa             VARCHAR(100)  NOT NULL,
    opis              TEXT,
    poziom_trudnosci  VARCHAR(20)   NOT NULL,

    CONSTRAINT pk_cwiczenie          PRIMARY KEY (id_cwiczenia),
    CONSTRAINT uq_cwiczenie_nazwa    UNIQUE (nazwa),

    CONSTRAINT chk_cwiczenie_poziom  CHECK (poziom_trudnosci IN ('poczatkujacy', 'sredniozaawansowany', 'zaawansowany'))
);

-- Cwiczenia_w_planie(#id_planu, #id_cwiczenia, liczba_serii, ilosc_powtorzen)
CREATE TABLE cwiczenia_w_planie (
    id_planu         INTEGER  NOT NULL,
    id_cwiczenia     INTEGER  NOT NULL,
    liczba_serii     INTEGER  NOT NULL,
    ilosc_powtorzen  INTEGER  NOT NULL,

    CONSTRAINT pk_cwiczenia_w_planie   PRIMARY KEY (id_planu, id_cwiczenia),
    CONSTRAINT fk_cwp_plan             FOREIGN KEY (id_planu)
        REFERENCES plan_treningowy (id_planu) ON DELETE CASCADE,
    CONSTRAINT fk_cwp_cwiczenie        FOREIGN KEY (id_cwiczenia)
        REFERENCES cwiczenie (id_cwiczenia) ON DELETE CASCADE,

    CONSTRAINT chk_cwp_serie           CHECK (liczba_serii > 0),
    CONSTRAINT chk_cwp_powtorzenia     CHECK (ilosc_powtorzen >= 0)
);

-- Wymagany_sprzet(#id_cwiczenia, #id_kategorii)
CREATE TABLE wymagany_sprzet (
    id_cwiczenia  INTEGER NOT NULL,
    id_kategorii  INTEGER NOT NULL,

    CONSTRAINT pk_wymagany_sprzet  PRIMARY KEY (id_cwiczenia, id_kategorii),
    CONSTRAINT fk_ws_cwiczenie     FOREIGN KEY (id_cwiczenia)
        REFERENCES cwiczenie (id_cwiczenia) ON DELETE CASCADE,
    CONSTRAINT fk_ws_kategoria     FOREIGN KEY (id_kategorii)
