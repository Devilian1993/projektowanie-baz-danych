BEGIN;

DROP TABLE IF EXISTS
    required_equipment, plan_exercise, exercise, training_plan,
    class_enrollment, group_class, trainer_qualification, class_type,
    station_reservation, training_payment, personal_training,
    service_request, machine, machine_model, station,
    membership_payment, payment, membership, membership_type, entry,
    administrator, technician, receptionist,
    trainer_specialization, specialization, trainer, client,
    failed_login, user_account, equipment_category, room
    CASCADE;

DROP DOMAIN IF EXISTS valid_email, valid_phone, valid_login;

-- E-mail address
CREATE DOMAIN valid_email AS VARCHAR(254)
CHECK (
    VALUE ~* '^[A-Za-z0-9._+%-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'
);

-- Phone number (contains only digits)
CREATE DOMAIN valid_phone AS VARCHAR(15)
CHECK (
    VALUE ~ '^[0-9]{9,15}$'
);

-- Login (can contain letters, numbers, dashes and underscores)
CREATE DOMAIN valid_login AS VARCHAR(50)
CHECK (
    VALUE ~ '^[A-Za-z0-9_-]+$'
);

-- Room(room_id, number, name, area, max_occupancy,
--      opening_time, closing_time, is_active)
CREATE TABLE room (
    room_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    number         INTEGER       NOT NULL,
    name           VARCHAR(100)  NOT NULL,
    area           NUMERIC(7,2),
    max_occupancy  INTEGER       NOT NULL,
    opening_time   TIME          NOT NULL DEFAULT '00:00',
    closing_time   TIME          NOT NULL DEFAULT '23:59:59',
    is_active      BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_room                 PRIMARY KEY (room_id),
    CONSTRAINT uq_room_number          UNIQUE (number),
    CONSTRAINT uq_room_name            UNIQUE (name),

    CONSTRAINT chk_room_number         CHECK (number >= 0),
    CONSTRAINT chk_room_area           CHECK (area > 0),
    CONSTRAINT chk_room_max_occupancy  CHECK (max_occupancy > 0),
    CONSTRAINT chk_room_time_range     CHECK (closing_time > opening_time)
);

-- Equipment_category(category_id, name, description)
CREATE TABLE equipment_category (
    category_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name         VARCHAR(100) NOT NULL,
    description  TEXT,

    CONSTRAINT pk_equipment_category  PRIMARY KEY (category_id),
    CONSTRAINT uq_category_name       UNIQUE (name)
);

-- User_account(account_id, login, email, password_hash, access_card_number,
--              is_active, created_at, last_login_at)
CREATE TABLE user_account (
    account_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    login               valid_login   NOT NULL,
    email               valid_email   NOT NULL,
    password_hash       VARCHAR(255)  NOT NULL,
    access_card_number  INTEGER       NOT NULL,
    is_active           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at       TIMESTAMP,

    CONSTRAINT pk_user_account          PRIMARY KEY (account_id),
    CONSTRAINT uq_account_login         UNIQUE (login),
    CONSTRAINT uq_account_email         UNIQUE (email),
    CONSTRAINT uq_account_card          UNIQUE (access_card_number),

    CONSTRAINT chk_account_card_number  CHECK (access_card_number >= 0),
    CONSTRAINT chk_account_time_range   CHECK (last_login_at >= created_at)
);

-- Failed_login(attempt_id, #account_id, attempted_at)
CREATE TABLE failed_login (
    attempt_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    account_id    INTEGER    NOT NULL,
    attempted_at  TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_failed_login          PRIMARY KEY (attempt_id),
    CONSTRAINT fk_failed_login_account  FOREIGN KEY (account_id)
        REFERENCES user_account (account_id) ON DELETE CASCADE
);

-- Client(client_id, #account_id, first_name, last_name, phone,
--        registered_at, is_student)
CREATE TABLE client (
    client_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    account_id     INTEGER       NOT NULL,
    first_name     VARCHAR(50)   NOT NULL,
    last_name      VARCHAR(80)   NOT NULL,
    phone          valid_phone,
    registered_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_student     BOOLEAN       NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_client          PRIMARY KEY (client_id),
    CONSTRAINT uq_client_account  UNIQUE (account_id),
    CONSTRAINT fk_client_account  FOREIGN KEY (account_id)
        REFERENCES user_account (account_id) ON DELETE CASCADE
);

-- Trainer(trainer_id, #account_id, first_name, last_name, phone,
--         hire_date, training_rate)
CREATE TABLE trainer (
    trainer_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    account_id     INTEGER        NOT NULL,
    first_name     VARCHAR(50)    NOT NULL,
    last_name      VARCHAR(80)    NOT NULL,
    phone          valid_phone,
    hire_date      DATE           NOT NULL DEFAULT CURRENT_DATE,
    -- NULL: trener prowadzi tylko zajęcia grupowe
    training_rate  NUMERIC(10,2),

    CONSTRAINT pk_trainer          PRIMARY KEY (trainer_id),
    CONSTRAINT uq_trainer_account  UNIQUE (account_id),
    CONSTRAINT fk_trainer_account  FOREIGN KEY (account_id)
        REFERENCES user_account (account_id) ON DELETE CASCADE,

    CONSTRAINT chk_trainer_rate    CHECK (training_rate >= 0)
);

-- Specialization(specialization_id, name, description)
CREATE TABLE specialization (
    specialization_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name               VARCHAR(100) NOT NULL,
    description        TEXT,

    CONSTRAINT pk_specialization       PRIMARY KEY (specialization_id),
    CONSTRAINT uq_specialization_name  UNIQUE (name)
);

-- Trainer_specialization(#trainer_id, #specialization_id)
CREATE TABLE trainer_specialization (
    trainer_id         INTEGER NOT NULL,
    specialization_id  INTEGER NOT NULL,

    CONSTRAINT pk_trainer_specialization  PRIMARY KEY (trainer_id, specialization_id),
    CONSTRAINT fk_ts_trainer              FOREIGN KEY (trainer_id)
        REFERENCES trainer (trainer_id) ON DELETE CASCADE,
    CONSTRAINT fk_ts_specialization       FOREIGN KEY (specialization_id)
        REFERENCES specialization (specialization_id) ON DELETE CASCADE
);

-- Receptionist(receptionist_id, #account_id, first_name, last_name, phone, hire_date)
CREATE TABLE receptionist (
    receptionist_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    account_id       INTEGER       NOT NULL,
    first_name       VARCHAR(50)   NOT NULL,
    last_name        VARCHAR(80)   NOT NULL,
    phone            valid_phone,
    hire_date        DATE          NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_receptionist          PRIMARY KEY (receptionist_id),
    CONSTRAINT uq_receptionist_account  UNIQUE (account_id),
    CONSTRAINT fk_receptionist_account  FOREIGN KEY (account_id)
        REFERENCES user_account (account_id) ON DELETE CASCADE
);

-- Technician(technician_id, #account_id, first_name, last_name, phone, hire_date)
CREATE TABLE technician (
    technician_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    account_id     INTEGER       NOT NULL,
    first_name     VARCHAR(50)   NOT NULL,
    last_name      VARCHAR(80)   NOT NULL,
    phone          valid_phone,
    hire_date      DATE          NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_technician          PRIMARY KEY (technician_id),
    CONSTRAINT uq_technician_account  UNIQUE (account_id),
    CONSTRAINT fk_technician_account  FOREIGN KEY (account_id)
        REFERENCES user_account (account_id) ON DELETE CASCADE
);

-- Administrator(administrator_id, #account_id, first_name, last_name, phone)
CREATE TABLE administrator (
    administrator_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    account_id        INTEGER       NOT NULL,
    first_name        VARCHAR(50)   NOT NULL,
    last_name         VARCHAR(80)   NOT NULL,
    phone             valid_phone,

    CONSTRAINT pk_administrator          PRIMARY KEY (administrator_id),
    CONSTRAINT uq_administrator_account  UNIQUE (account_id),
    CONSTRAINT fk_administrator_account  FOREIGN KEY (account_id)
        REFERENCES user_account (account_id) ON DELETE CASCADE
);

-- Entry(entry_id, #account_id, entered_at, exited_at, result, denial_reason)
CREATE TABLE entry (
    entry_id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    account_id     INTEGER       NOT NULL,
    entered_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    exited_at      TIMESTAMP,
    result         BOOLEAN       NOT NULL,
    denial_reason  VARCHAR(255),

    CONSTRAINT pk_entry              PRIMARY KEY (entry_id),
    CONSTRAINT fk_entry_account      FOREIGN KEY (account_id)
        REFERENCES user_account (account_id) ON DELETE CASCADE,

    CONSTRAINT chk_entry_time_range  CHECK (exited_at > entered_at),
    CONSTRAINT chk_entry_result      CHECK (result OR exited_at IS NULL),
    -- powód podaje się wtedy i tylko wtedy, gdy wejścia odmówiono
    CONSTRAINT chk_entry_reason      CHECK (result = (denial_reason IS NULL))
);

-- Membership_type(type_id, name, validity_period, regular_price, reduced_price, description)
CREATE TABLE membership_type (
    type_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name             VARCHAR(50)    NOT NULL,
    -- w dniach
    validity_period  INTEGER        NOT NULL,
    regular_price    NUMERIC(10,2)  NOT NULL,
    reduced_price    NUMERIC(10,2)  NOT NULL,
    description      TEXT,

    CONSTRAINT pk_membership_type      PRIMARY KEY (type_id),
    CONSTRAINT uq_type_name            UNIQUE (name),

    CONSTRAINT chk_type_period         CHECK (validity_period >= 1),
    CONSTRAINT chk_type_regular_price  CHECK (regular_price >= 0),
    CONSTRAINT chk_type_reduced_price  CHECK (reduced_price >= 0),
    CONSTRAINT chk_type_prices         CHECK (reduced_price <= regular_price)
);

-- Membership(membership_id, #client_id, #type_id, #receptionist_id,
--            purchase_date, start_date, price)
CREATE TABLE membership (
    membership_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    client_id        INTEGER        NOT NULL,
    type_id          INTEGER        NOT NULL,
    receptionist_id  INTEGER,
    purchase_date    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    start_date       DATE           NOT NULL DEFAULT CURRENT_DATE,
    price            NUMERIC(10,2)  NOT NULL,

    CONSTRAINT pk_membership               PRIMARY KEY (membership_id),
    CONSTRAINT fk_membership_client        FOREIGN KEY (client_id)
        REFERENCES client (client_id) ON DELETE CASCADE,
    CONSTRAINT fk_membership_type          FOREIGN KEY (type_id)
        REFERENCES membership_type (type_id) ON DELETE RESTRICT,
    CONSTRAINT fk_membership_receptionist  FOREIGN KEY (receptionist_id)
        REFERENCES receptionist (receptionist_id) ON DELETE SET NULL,

    CONSTRAINT chk_membership_price        CHECK (price >= 0),
    CONSTRAINT chk_membership_time_range   CHECK (start_date >= purchase_date::date)
);

-- Payment(payment_id, amount, payment_date, method, purpose, status)
CREATE TABLE payment (
    payment_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    amount        NUMERIC(10,2)  NOT NULL,
    payment_date  TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    method        VARCHAR(15)    NOT NULL,
    purpose       VARCHAR(20)    NOT NULL,
    status        VARCHAR(15)    NOT NULL DEFAULT 'oczekujaca',

    CONSTRAINT pk_payment          PRIMARY KEY (payment_id),

    CONSTRAINT chk_payment_amount  CHECK (amount >= 0),
    CONSTRAINT chk_payment_method  CHECK (method IN ('gotowka', 'blik', 'karta')),
    CONSTRAINT chk_payment_status  CHECK (status IN ('oczekujaca', 'oplacona', 'odrzucona'))
);

-- Membership_payment(#payment_id, #membership_id)
CREATE TABLE membership_payment (
    payment_id     INTEGER NOT NULL,
    membership_id  INTEGER NOT NULL,

    CONSTRAINT pk_membership_payment  PRIMARY KEY (payment_id, membership_id),
    CONSTRAINT fk_mp_payment          FOREIGN KEY (payment_id)
        REFERENCES payment (payment_id) ON DELETE CASCADE,
    -- RESTRICT: opłaconego karnetu nie można usunąć (historia płatności)
    CONSTRAINT fk_mp_membership       FOREIGN KEY (membership_id)
        REFERENCES membership (membership_id) ON DELETE RESTRICT
);

-- Station(station_id, #room_id, name, description, is_available)
CREATE TABLE station (
    station_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    room_id       INTEGER       NOT NULL,
    name          VARCHAR(100)  NOT NULL,
    description   TEXT,
    is_available  BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_station       PRIMARY KEY (station_id),
    CONSTRAINT fk_station_room  FOREIGN KEY (room_id)
        REFERENCES room (room_id) ON DELETE CASCADE
);

-- Machine_model(model_id, #category_id, manufacturer, model, name)
CREATE TABLE machine_model (
    model_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    category_id   INTEGER       NOT NULL,
    manufacturer  VARCHAR(100)  NOT NULL,
    model         VARCHAR(100)  NOT NULL,
    name          VARCHAR(150),

    CONSTRAINT pk_machine_model       PRIMARY KEY (model_id),
    CONSTRAINT uq_model_manufacturer  UNIQUE (manufacturer, model),
    CONSTRAINT fk_model_category      FOREIGN KEY (category_id)
        REFERENCES equipment_category (category_id) ON DELETE RESTRICT
);

-- Machine(machine_id, #station_id, #model_id, serial_number,
--         purchase_date, tech_condition, maintenance_date)
CREATE TABLE machine (
    machine_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    station_id        INTEGER,                  -- NULL: maszyna w magazynie / w serwisie
    model_id          INTEGER       NOT NULL,
    serial_number     VARCHAR(50)   NOT NULL,
    purchase_date     DATE          NOT NULL,
    tech_condition    VARCHAR(20)   NOT NULL DEFAULT 'sprawna',
    maintenance_date  DATE,

    CONSTRAINT pk_machine              PRIMARY KEY (machine_id),
    CONSTRAINT uq_machine_number       UNIQUE (model_id, serial_number),
    CONSTRAINT fk_machine_station      FOREIGN KEY (station_id)
        REFERENCES station (station_id) ON DELETE SET NULL,
    -- RESTRICT: nie można usunąć modelu, dopóki istnieją maszyny tego modelu
    CONSTRAINT fk_machine_model        FOREIGN KEY (model_id)
        REFERENCES machine_model (model_id) ON DELETE RESTRICT,

    CONSTRAINT chk_machine_condition   CHECK (tech_condition IN ('sprawna', 'uszkodzona', 'w_konserwacji')),
    CONSTRAINT chk_machine_time_range  CHECK (maintenance_date >= purchase_date)
);

-- Service_request(request_id, #machine_id, #reporter_account_id,
--                 #technician_id, request_type, reported_at, description,
--                 start_date, end_date)
CREATE TABLE service_request (
    request_id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    machine_id           INTEGER       NOT NULL,
    reporter_account_id  INTEGER,
    technician_id        INTEGER,                  -- NULL: jeszcze nie przydzielono technika
    request_type         VARCHAR(25)   NOT NULL,
    reported_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    description          TEXT          NOT NULL,
    start_date           TIMESTAMP,                -- NULL do chwili podjęcia naprawy
    end_date             TIMESTAMP,

    CONSTRAINT pk_service_request      PRIMARY KEY (request_id),
    CONSTRAINT fk_request_machine      FOREIGN KEY (machine_id)
        REFERENCES machine (machine_id) ON DELETE CASCADE,
    CONSTRAINT fk_request_account      FOREIGN KEY (reporter_account_id)
        REFERENCES user_account (account_id) ON DELETE SET NULL,
    CONSTRAINT fk_request_technician   FOREIGN KEY (technician_id)
        REFERENCES technician (technician_id) ON DELETE SET NULL,

    CONSTRAINT chk_request_type        CHECK (request_type IN ('rutynowa_konserwacja', 'uszkodzona_czesc', 'brakujaca_czesc', 'zuzyta_czesc')),
    CONSTRAINT chk_request_start       CHECK (start_date >= reported_at),
    CONSTRAINT chk_request_end         CHECK (end_date > start_date),
    CONSTRAINT chk_request_valid_time  CHECK (end_date IS NULL OR start_date IS NOT NULL)
);

-- Personal_training(training_id, #client_id, #trainer_id,
--                   starts_at, ends_at, price, is_cancelled, notes)
CREATE TABLE personal_training (
    training_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    client_id     INTEGER        NOT NULL,
    trainer_id    INTEGER        NOT NULL,
    starts_at     TIMESTAMP      NOT NULL,
    ends_at       TIMESTAMP      NOT NULL,
    -- cena z chwili umówienia treningu
    price         NUMERIC(10,2)  NOT NULL,
    is_cancelled  BOOLEAN        NOT NULL DEFAULT FALSE,
    notes         TEXT,

    CONSTRAINT pk_personal_training     PRIMARY KEY (training_id),
    CONSTRAINT fk_training_client       FOREIGN KEY (client_id)
        REFERENCES client (client_id) ON DELETE CASCADE,
    -- RESTRICT: trenera z historią treningów nie usuwa się (dezaktywacja konta)
    CONSTRAINT fk_training_trainer      FOREIGN KEY (trainer_id)
        REFERENCES trainer (trainer_id) ON DELETE RESTRICT,

    CONSTRAINT chk_training_price       CHECK (price >= 0),
    CONSTRAINT chk_training_time_range  CHECK (ends_at > starts_at)
);

-- Training_payment(#payment_id, #training_id)
CREATE TABLE training_payment (
    payment_id   INTEGER NOT NULL,
    training_id  INTEGER NOT NULL,

    CONSTRAINT pk_training_payment  PRIMARY KEY (payment_id, training_id),
    CONSTRAINT fk_tp_payment        FOREIGN KEY (payment_id)
        REFERENCES payment (payment_id) ON DELETE CASCADE,
    -- RESTRICT: opłaconego treningu nie można usunąć (historia płatności)
    CONSTRAINT fk_tp_training       FOREIGN KEY (training_id)
        REFERENCES personal_training (training_id) ON DELETE RESTRICT
);

-- Station_reservation(reservation_id, #station_id, #training_id,
--                     reserved_from, reserved_to, created_at, is_active)
CREATE TABLE station_reservation (
    reservation_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    station_id      INTEGER      NOT NULL,
    training_id     INTEGER      NOT NULL,
    reserved_from   TIMESTAMP    NOT NULL,
    reserved_to     TIMESTAMP    NOT NULL,
