-- Training_plan(plan_id, #client_id, #trainer_id, name, goal,
--               valid_from, valid_to, recommendations)
CREATE TABLE training_plan (
    plan_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    client_id        INTEGER       NOT NULL,
    trainer_id       INTEGER       NOT NULL,
    name             VARCHAR(100)  NOT NULL,
    goal             VARCHAR(255),
    valid_from       DATE          NOT NULL,
    valid_to         DATE          NOT NULL,
    recommendations  TEXT,

    CONSTRAINT pk_training_plan     PRIMARY KEY (plan_id),
    CONSTRAINT fk_plan_client       FOREIGN KEY (client_id)
        REFERENCES client (client_id) ON DELETE CASCADE,
    CONSTRAINT fk_plan_trainer      FOREIGN KEY (trainer_id)
        REFERENCES trainer (trainer_id) ON DELETE CASCADE,

    CONSTRAINT chk_plan_time_range  CHECK (valid_to >= valid_from)
);

-- Exercise(exercise_id, name, description, difficulty_level)
CREATE TABLE exercise (
    exercise_id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name              VARCHAR(100)  NOT NULL,
    description       TEXT,
    difficulty_level  VARCHAR(20)   NOT NULL,

    CONSTRAINT pk_exercise         PRIMARY KEY (exercise_id),
    CONSTRAINT uq_exercise_name    UNIQUE (name),

    CONSTRAINT chk_exercise_level  CHECK (difficulty_level IN ('poczatkujacy', 'sredniozaawansowany', 'zaawansowany'))
);

-- Plan_exercise(#plan_id, #exercise_id, set_count, rep_count)
CREATE TABLE plan_exercise (
    plan_id      INTEGER  NOT NULL,
    exercise_id  INTEGER  NOT NULL,
    set_count    INTEGER  NOT NULL,
    rep_count    INTEGER  NOT NULL,

    CONSTRAINT pk_plan_exercise  PRIMARY KEY (plan_id, exercise_id),
    CONSTRAINT fk_pe_plan        FOREIGN KEY (plan_id)
        REFERENCES training_plan (plan_id) ON DELETE CASCADE,
    CONSTRAINT fk_pe_exercise    FOREIGN KEY (exercise_id)
        REFERENCES exercise (exercise_id) ON DELETE CASCADE,

    CONSTRAINT chk_pe_sets       CHECK (set_count > 0),
    CONSTRAINT chk_pe_reps       CHECK (rep_count >= 0)
);

-- Required_equipment(#exercise_id, #category_id)
CREATE TABLE required_equipment (
    exercise_id  INTEGER NOT NULL,
    category_id  INTEGER NOT NULL,

    CONSTRAINT pk_required_equipment  PRIMARY KEY (exercise_id, category_id),
    CONSTRAINT fk_re_exercise         FOREIGN KEY (exercise_id)
        REFERENCES exercise (exercise_id) ON DELETE CASCADE,
    CONSTRAINT fk_re_category         FOREIGN KEY (category_id)
        REFERENCES equipment_category (category_id) ON DELETE CASCADE
);

COMMIT;
