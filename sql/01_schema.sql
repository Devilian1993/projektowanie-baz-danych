    CONSTRAINT fk_reservation_training     FOREIGN KEY (training_id)
        REFERENCES personal_training (training_id) ON DELETE CASCADE,

    CONSTRAINT chk_reservation_time_range  CHECK (reserved_to > reserved_from)
